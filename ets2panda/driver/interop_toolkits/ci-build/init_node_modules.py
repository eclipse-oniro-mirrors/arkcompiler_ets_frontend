"""Copy node_modules from one package to other packages inside a workspace."""

import argparse
import os
import shutil
import sys


def parse_args():
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--workspace",
        required=True,
        help="workspace directory that contains all packages",
    )
    parser.add_argument(
        "--from",
        dest="source_package",
        required=True,
        help="package name that contains node_modules",
    )
    parser.add_argument(
        "--to",
        nargs="+",
        required=True,
        help="package names that need node_modules",
    )
    parser.add_argument(
        "--exclude",
        nargs="+",
        default=[],
        metavar="ENTRY",
        help="node_modules entries (e.g. @interop-toolkits/common) that are "
        "not copied; entries installed from built tarballs (install_pkg.py) "
        "must not be distributed from a development node_modules copy",
    )
    return parser.parse_args()


def copy_node_modules(workspace, source_package, target_packages, excludes):
    source_node_modules = os.path.join(workspace, source_package, "node_modules")
    if not os.path.isdir(source_node_modules):
        raise FileNotFoundError(
            "source node_modules not found: {}".format(source_node_modules)
        )

    normalized_excludes = {entry.replace(os.sep, "/") for entry in excludes}

    def ignore(directory, names):
        skipped = set()
        for name in names:
            relative = os.path.relpath(
                os.path.join(directory, name), source_node_modules
            )
            if relative.replace(os.sep, "/") in normalized_excludes:
                skipped.add(name)
        return skipped

    for target_package in target_packages:
        target_node_modules = os.path.join(
            workspace, target_package, "node_modules"
        )
        shutil.rmtree(target_node_modules, ignore_errors=True)
        shutil.copytree(
            source_node_modules, target_node_modules, symlinks=True, ignore=ignore
        )


def main():
    options = parse_args()
    copy_node_modules(
        options.workspace, options.source_package, options.to, options.exclude
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
