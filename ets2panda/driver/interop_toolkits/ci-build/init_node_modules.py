"""Copy node_modules from one package to other packages inside a workspace."""

import argparse
import os
import shutil
import sys


def parse_args():
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--workspace",
        required=True,
        help="workspace directory that contains all packages",
    )
    parser.add_argument(
        "--from",
        dest="source_package",
        required=True,
        help="package name that contains node_modules",
    )
    parser.add_argument(
        "--to",
        nargs="+",
        required=True,
        help="package names that need node_modules",
    )
    return parser.parse_args()


def copy_node_modules(workspace, source_package, target_packages):
    source_node_modules = os.path.join(workspace, source_package, "node_modules")
    if not os.path.isdir(source_node_modules):
        raise FileNotFoundError(
            "source node_modules not found: {}".format(source_node_modules)
        )

    for target_package in target_packages:
        target_node_modules = os.path.join(
            workspace, target_package, "node_modules"
        )
        shutil.rmtree(target_node_modules, ignore_errors=True)
        shutil.copytree(source_node_modules, target_node_modules, symlinks=True)


def main():
    options = parse_args()
    copy_node_modules(options.workspace, options.source_package, options.to)
    return 0


if __name__ == "__main__":
    sys.exit(main())
